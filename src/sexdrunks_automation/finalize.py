from datetime import datetime, timezone
from pathlib import Path
from typing import List, Optional

from sexdrunks_automation.models import SessionRecord, SessionStatus
from sexdrunks_automation.repository import (
    get_episode,
    get_session,
    update_session_status,
    upsert_episode_metadata,
)


class FinalizeError(RuntimeError):
    pass


def finalize_session(
    *,
    db_file: str,
    session: SessionRecord,
    master_path: Path,
) -> SessionRecord:
    if session.status != SessionStatus.WAITING_FOR_FINALIZE.value:
        raise FinalizeError(
            f"Session {session.session_uid} must be waiting_for_finalize before finalize"
        )
    if not session.transcript_path:
        raise FinalizeError(f"Session {session.session_uid} has no transcript path")
    if not Path(session.transcript_path).exists():
        raise FinalizeError(f"Transcript file not found: {session.transcript_path}")
    if not session.pre_edit_master_path:
        raise FinalizeError(
            f"Session {session.session_uid} has no pre-edit master path"
        )
    if not Path(session.pre_edit_master_path).exists():
        raise FinalizeError(
            f"Pre-edit master file not found: {session.pre_edit_master_path}"
        )

    resolved_master_path = master_path.expanduser().resolve()
    if not resolved_master_path.exists():
        raise FinalizeError(f"Final master file not found: {resolved_master_path}")
    if resolved_master_path.suffix.lower() not in {
        ".mp3",
        ".wav",
        ".m4a",
        ".aif",
        ".aiff",
    }:
        raise FinalizeError(
            f"Unsupported final master format: {resolved_master_path.suffix}"
        )

    title, description = generate_metadata(
        transcript_path=Path(session.transcript_path),
        source_basename=session.source_basename,
    )
    upsert_episode_metadata(
        db_file,
        session_uid=session.session_uid,
        title=title,
        description=description,
    )

    timestamp = datetime.now(timezone.utc).isoformat()
    update_session_status(
        db_file,
        session_uid=session.session_uid,
        from_state=session.status,
        to_state=SessionStatus.READY_FOR_DRAFT.value,
        timestamp=timestamp,
        detail="finalized session with edited master and generated metadata",
        final_master_path=str(resolved_master_path),
        failure_reason=None,
        failed_at_stage=None,
    )
    updated = get_session(db_file, session.session_uid)
    if updated is None:
        raise FinalizeError(f"Finalized session disappeared: {session.session_uid}")
    return updated


def generate_metadata(
    *, transcript_path: Path, source_basename: Optional[str]
) -> tuple[str, str]:
    transcript_text = transcript_path.read_text(encoding="utf-8")
    lines = _clean_transcript_lines(transcript_text)
    excerpt_lines = lines[:6]
    excerpt = " ".join(excerpt_lines).strip()
    title_seed = (
        excerpt_lines[0] if excerpt_lines else (source_basename or transcript_path.stem)
    )
    title = f"Sex Drunks - {_truncate_words(title_seed, 12)}"

    description_parts = []
    if source_basename:
        description_parts.append(f"Session: {source_basename}")
    if excerpt:
        description_parts.append(f"Transcript excerpt: {excerpt}")
    description_parts.append(
        "Generated by automation from the Auphonic transcript. Review in Podbean before publishing."
    )
    return title, "\n\n".join(description_parts)


def _clean_transcript_lines(transcript_text: str) -> List[str]:
    lines: List[str] = []
    for raw_line in transcript_text.splitlines():
        line = raw_line.strip()
        if not line or line == "WEBVTT" or "-->" in line:
            continue
        if line.isdigit():
            continue
        lines.append(line)
    return lines


def _truncate_words(text: str, max_words: int) -> str:
    words = text.split()
    if len(words) <= max_words:
        return text.strip()
    return " ".join(words[:max_words]).strip() + "..."


def get_episode_metadata(db_file: str, session_uid: str):
    return get_episode(db_file, session_uid)
